async function main() {
  console.log("📝 seeding 10 articles...");
  for (const a of ARTICLES) {
    const existing = await db.blogPost.findUnique({ where: { slug: a.slug } });
    if (existing) {
      console.log(`  ⚠️ ${a.slug} exists, skipping`);
      continue;
    }
    const readingTime = Math.max(2, Math.ceil(a.paragraphs.join(" ").split(/\s+/).length / 180));
    await db.blogPost.create({
      data: {
        title: a.title,
        slug: a.slug,
        excerpt: a.excerpt,
        content: htmlFromParagraphs(a.paragraphs, a.h2Headings),
        tiptapContent: tipDoc(a.paragraphs, a.h2Headings),
        coverImage: a.coverImage,
        readingTime,
        category: a.category,
        tags: a.tags,
        status: "published",
        featured: a.featured,
        publishedAt: new Date(),
        // authorId null = "كاتب المنصة"
      },
    });
    console.log(`  ✅ ${a.slug}`);
  }
  console.log("\n✅ Done. Articles count:");
  const total = await db.blogPost.count();
  console.log(`   ${total} مقالاً في القاعدة`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await db.$disconnect();
  });
