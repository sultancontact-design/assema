interface TipTapDoc {
  type: "doc";
  content: Array<{
    type: "paragraph" | "heading";
    attrs?: { level?: number };
    content?: Array<{ type: "text"; text: string }>;
  }>;
}

function tipDoc(paragraphs: string[], h2Headings: { idx: number; text: string }[] = []): string {
  const content: TipTapDoc["content"] = [];
  paragraphs.forEach((text, i) => {
    const heading = h2Headings.find((h) => h.idx === i);
    if (heading) {
      content.push({ type: "heading", attrs: { level: 2 }, content: [{ type: "text", text: heading.text }] });
    }
    content.push({ type: "paragraph", content: [{ type: "text", text }] });
  });
  return JSON.stringify({ type: "doc", content });
}

function htmlFromParagraphs(paragraphs: string[], h2Headings: { idx: number; text: string }[] = []): string {
  return paragraphs
    .map((p, i) => {
      const heading = h2Headings.find((h) => h.idx === i);
      return (heading ? `<h2>${heading.text}</h2>` : "") + `<p>${p}</p>`;
    })
    .join("\n");
}

